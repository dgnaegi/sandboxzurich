import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--use-gl=angle'] });
const p = await (await b.newContext({ viewport: { width: 800, height: 450 } })).newPage();
p.on('pageerror', (e) => console.log('pageerror', e.message));
await p.goto('http://localhost:5173/?at=-101,-93,0.6&t=13:00');
await p.waitForFunction(() => window.sbxReady, null, { timeout: 60000 });
await p.waitForTimeout(3000);
const r = await p.evaluate(() => { const P = window.sbxPlayer; const g = P.tiles.ground(P.x, P.y); P.z = -2.99; return { ground: g }; });
await p.keyboard.down('w'); await p.waitForTimeout(2500); await p.keyboard.up('w');
const s = await p.evaluate(() => { const P = window.sbxPlayer; return { x: P.x, y: P.y, z: P.z, ground: P.tiles.ground(P.x, P.y), deck: P.tiles.bridges.heightAt(P.x, P.y, P.z) }; });
console.log(JSON.stringify(r), JSON.stringify(s));
await p.screenshot({ path: '../preview/bridge.png' });
await b.close();
